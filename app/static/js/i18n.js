document.addEventListener('DOMContentLoaded', () => {
  initLanguageSwitcher();
});

function initLanguageSwitcher() {
  const savedLang = localStorage.getItem('civicfix-lang') || 'en';
  setLanguage(savedLang);

  const langSelect = document.getElementById('lang-select');
  if (langSelect) {
    langSelect.value = savedLang;
    langSelect.addEventListener('change', (e) => {
      const selected = e.target.value;
      localStorage.setItem('civicfix-lang', selected);
      setLanguage(selected);
      // Dispatch custom event for map or AI assistant re-render
      window.dispatchEvent(new CustomEvent('civicfix-lang-changed', { detail: { lang: selected } }));
    });
  }
}

function setLanguage(lang) {
  const dict = translations[lang] || translations.en;
  const fallback = translations.en;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const text = dict[key] || fallback[key];
    if (text) {
      if (el.tagName === 'INPUT' && (el.type === 'button' || el.type === 'submit')) {
        el.value = text;
      } else {
        el.textContent = text;
      }
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    const text = dict[key] || fallback[key];
    if (text) {
      el.setAttribute('placeholder', text);
    }
  });
}

// Global translation lookup helper
window.t = function(key) {
  const currentLang = localStorage.getItem('civicfix-lang') || 'en';
  const dict = translations[currentLang] || translations.en;
  return dict[key] || translations.en[key] || key;
};
